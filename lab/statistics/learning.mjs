export function dataStep(id) {
  if (id === "probability")
    return step(
      "実験の準備",
      "実験",
      "コインの条件を決め、1行が1セットの結果になる実験を作る。",
      "表の確率・1セットの投数・実験するセット数を設定します。",
    );
  return step(
    "データ",
    "データ確認",
    id === "sampling"
      ? "1行が母集団の1件を表します。何を調べる集団か、値と単位を確認します。"
      : id === "crosstab"
        ? "1行が1人分です。3つの属性を確認します。"
        : id === "hypothesis-test"
          ? "2群の対象人数と該当人数を確認し、割合の比較へ進みます。"
          : id === "time-series"
            ? "1行が1か月の値です。時間順・単位・データの出所を確認します。"
            : id === "probability"
              ? "コインの0/1・1セットの成功回数・連続値から種類を選び、実験または読込の値を確認します。"
              : "1行が何を表すか、項目名・単位・値の対応を確かめてから、グラフへ進みます。",
    "サンプル・表への入力・CSVの読み込みで、分析するデータを用意します。",
  );
}
export function renderStepNavigation(container, steps, index, go) {
  container.innerHTML = `<div class="step-buttons">${index ? `<button id="step-prev" type="button">← ${esc(steps[index - 1].title)}</button>` : ""}<span>${index + 1} / ${steps.length}</span>${index + 1 < steps.length ? `<button id="step-next" class="primary" type="button">次へ：${esc(steps[index + 1].title)} →</button>` : ""}</div>`;
  container
    .querySelector("#step-prev")
    ?.addEventListener("click", () => go(index - 1));
  container
    .querySelector("#step-next")
    ?.addEventListener("click", () => go(index + 1));
}
