export function learningViews(id, state = {}) {
  if (id !== "probability") return learning[id];
  if (state.mode === "binomial")
    return [
      step(
        "二項分布",
        "発展",
        "n回の試行を1セットにし、成功回数の分布を作る。",
        "1セットのnと反復セット数は別です。棒は実験の相対度数、橙の点は同じn・pでの理論確率です。",
      ),
      step(
        "理論確率の表",
        "発展",
        "成功回数ごとの度数・相対度数と二項分布の理論確率を比べる。",
        "独立・同じ成功確率という仮定を確認します。実験の割合は揺れますが、理論確率はnとpで決まります。",
      ),
    ];
  if (state.mode === "normal")
    return [
      step(
        "正規分布",
        "発展",
        "区間に入る確率を、曲線の高さではなく面積で捉える。",
        "平均・標準偏差・区間を変えてみましょう。読込データの区間内割合と、正規モデルの理論確率は別の量です。",
      ),
      step(
        "標準化",
        "発展",
        "Z=(X−平均)÷標準偏差で単位を外し、同じ面積を読む。",
        "元の区間とzの区間を対応させます。観測値を標準化するだけで、その分布が正規分布になるわけではありません。",
      ),
    ];
  return [
    step(
      "相対度数",
      "基本",
      "偶然の結果を繰り返し、表の割合がどう揺れるかを見る。",
      "回数を追加してみましょう。独立な試行では、表が続いても次に裏が出やすくなることはありません。",
    ),
  ];
}
export function dataStep(id) {
  return step(
    "データ",
    "データ確認",
    id === "sampling"
      ? "1行が母集団の1件を表します。何を調べる集団か、値と単位を確認します。"
      : id === "crosstab"
        ? "1行が1集団×1方式の集計です。成功・不成功の人数を確認します。"
        : id === "hypothesis-test"
          ? "AとBの対象人数と成功人数を確認し、割合の比較へ進みます。"
          : id === "time-series"
            ? "1行が1か月の値です。時間順と単位を確認し、48か月の前半36か月・後半12か月を区別します。"
            : id === "probability"
              ? "コインの0/1・1セットの成功回数・連続値から種類を選び、実験または読込の値を確認します。"
              : "1行が何を表すか、項目名・単位・値の対応を確かめてから、グラフへ進みます。",
    "サンプル・表への入力・CSVの読み込みで、分析するデータを用意します。",
  );
}
export function renderStepNavigation(container, steps, index, go) {
  container.innerHTML = `<div class="step-buttons">${index ? `<button id="step-prev" type="button">← ${esc(steps[index - 1].title)}</button>` : ""}<span>${index + 1} / ${steps.length}</span>${index + 1 < steps.length ? `<button id="step-next" class="primary" type="button">次へ：${esc(steps[index + 1].title)} →</button>` : ""}</div>`;
  container
    .querySelector("#step-prev")
    ?.addEventListener("click", () => go(index - 1));
  container
    .querySelector("#step-next")
    ?.addEventListener("click", () => go(index + 1));
}
