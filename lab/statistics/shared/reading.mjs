export function readingNotes(id, view = 0, state = {}) {
  if (id === "probability") {
    if (state.mode === "normal")
      return view === 0
        ? [
            "正規分布は、平均を中心とする左右対称の分布です。",
            "曲線の下の面積が確率です。平均・標準偏差と区間を変えてみましょう。",
          ]
        : [
            "標準化した値z＝(値−平均)÷標準偏差です。",
            "平均から標準偏差の何倍離れているかで、値の位置を比べましょう。",
          ];
    if (state.mode === "binomial")
      return [
        "二項分布は、同じ成功確率で独立にn回試したときの成功回数の分布です。",
        "実験の棒と理論確率を比べ、nや成功確率pを変えてみましょう。",
      ];
    return [
      "相対度数＝その結果が出た回数÷試行回数です。",
      "試行を増やし、相対度数が確率pの近くに安定する様子を見ましょう。",
    ];
  }
  return notes[id]?.[view] || [];
}

