import { readFile, writeFile } from "node:fs/promises";
const model = await readFile(
  new URL("../digital-audio/pcm.mjs", import.meta.url),
  "utf8",
);
const worker =
  model.replace(/^export /gm, "") +
  `
let reference, referenceKey;
self.onmessage = ({ data }) => {
  try {
    const key = JSON.stringify([data.config.source, data.config.tone]);
    if (key !== referenceKey) { reference = referenceAudio(data.config); referenceKey = key; }
    const output = digitizeAudio(data.config);
    const copy = reference.slice();
    self.postMessage({ ...data, ...output, reference: copy },
      [copy.buffer, output.raw.buffer, output.quantized.buffer, output.codes.buffer, output.processed.buffer]);
  } catch (error) { self.postMessage({ id: data.id, error: error.message }); }
};
`;
const content = `// Generated by tools/build-audio-worker.mjs from pcm.mjs.\nexport const audioWorkerSource = ${JSON.stringify(worker)};\n`;
const target = new URL("../digital-audio/worker-source.mjs", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== content)
    throw new Error("worker-source.mjs is out of date");
} else await writeFile(target, content);
