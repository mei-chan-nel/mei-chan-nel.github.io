// Embed a classic worker so both the website and downloadable HTML run offline.
import { readFile, writeFile } from "node:fs/promises";
const model = await readFile(
  new URL("../digital-image/pixels.mjs", import.meta.url),
  "utf8",
);
const source =
  model.replace(/^export /gm, "") +
  `
let source, averages, lastSize;
self.onmessage = ({data}) => {
  if (data.type === "source") {
    source = integralImage(data.pixels, data.width, data.height);
    averages = undefined; lastSize = undefined;
    self.postMessage({type:"ready", version:data.version});
  } else {
    if (lastSize !== data.size) { averages = averagePixels(source,data.size); lastSize = data.size; }
    const pixels = convertPixels(averages,data.settings);
    self.postMessage({...data,pixels},[pixels.buffer]);
  }
};
`;
const module = `// Generated by tools/build-render-worker.mjs from pixels.mjs.\nexport const renderWorkerSource = ${JSON.stringify(source)};\n`;
const target = new URL("../digital-image/render-source.mjs", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== module)
    throw new Error("render-source.mjs is out of date");
} else await writeFile(target, module);
